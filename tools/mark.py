# xvlet's mark: an x of two arcs back to back -- ")(" -- nearly touching
# in the middle, their round ends apart. One colour; two parts that move
# (spread apart, turn).
#
#   python tools/mark.py assets/brand/xvlet.svg components/XvletMark.qml
import math, sys

S = 512
C = S / 2
R = 200          # the arcs' radius
W = 66           # their thickness
GAP = 8          # between them in the middle
SPAN = 60        # each arc: this many degrees either side of its middle

def arc(sign):
    # sign -1: ")" left of the middle, bulging right; +1: "(" mirrored
    cx = C + sign * (GAP / 2 + W / 2 + R) * -1 if sign < 0 else C + (GAP / 2 + W / 2 + R)
    cx = C - (GAP / 2 + W / 2 + R) if sign < 0 else C + (GAP / 2 + W / 2 + R)
    a0, a1 = math.radians(-SPAN), math.radians(SPAN)
    if sign > 0:
        a0, a1 = math.pi - a1, math.pi - a0
    p0 = (cx + R * math.cos(a0), C + R * math.sin(a0))
    p1 = (cx + R * math.cos(a1), C + R * math.sin(a1))
    return "M%.1f %.1f A%d %d 0 0 1 %.1f %.1f" % (p0 + (R, R) + p1)

left, right = arc(-1), arc(1)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" width="{S}" height="{S}">
  <title>xvlet</title>
  <!-- xvlet's mark (tools/mark.py): an x of two arcs back to back. One
       colour: currentColor (the CSS variable ink). Parts: #left, #right. -->
  <g style="fill:none;stroke:var(--ink, currentColor);stroke-width:{W};stroke-linecap:round">
    <path id="left" d="{left}"/>
    <path id="right" d="{right}"/>
  </g>
</svg>
'''
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write(svg)

