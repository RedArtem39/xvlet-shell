# xvlet's mark: wings of shards -- a faceted V (a folded-paper bird, or a
# pair of glasses), the right wing drawn and mirrored, each facet in one of
# three tones. Every shard is its own part: the QML can scatter them and
# bring them back, and beat the wings.
#
#   python tools/mark.py assets/brand/xvlet.svg components/XvletMark.qml
import math, sys

S = 512
C = S / 2

# the right wing and the right half of the body, in a box centred on (0, 0);
# (tone 0 the ink, 1 a step lighter, 2 lighter still)
RIGHT = [
    ("wing", 1, [(4, 26), (62, -2), (150, -150)]),              # the wing's upper face
    ("wing", 0, [(4, 26), (150, -150), (30, -30)]),             # its leading edge
    ("wing", 0, [(30, -30), (150, -150), (96, -60)]),           # the tip's fold
    ("low", 1, [(26, 30), (118, -18), (126, -10), (44, 48)]),  # the lower feather
    ("low", 2, [(118, -18), (150, 2), (126, -10)]),            # its point
    ("body", 0, [(0, 22), (54, 12), (0, 82)]),                 # the body
    ("body", 2, [(0, 82), (54, 12), (30, 48)]),
]
def mirror(p): return [(-x, y) for x, y in p]
SHARDS = []
for side in (1, -1):
    for part, tone, pts in RIGHT:
        SHARDS.append((part, side, tone, pts if side > 0 else mirror(pts)))

def poly(pts, ox=C, oy=C + 30):
    return "M" + " L".join("%.1f %.1f" % (x + ox, y + oy) for x, y in pts) + " Z"

def centroid(pts):
    return (sum(x for x, _ in pts) / len(pts) + C, sum(y for _, y in pts) / len(pts) + C + 30)

TONES = ["var(--ink, #1b1d24)", "var(--ink2, #3a3f4c)", "var(--ink3, #626879)"]
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{C - 170} {C - 150} 340 340" width="{S}" height="{S}">',
       '  <title>xvlet</title>',
       '  <!-- xvlet\'s mark (tools/mark.py): wings of shards. Three tones (the CSS',
       '       variables ink, ink2, ink3); every shard a path of its own. -->']
for i, (part, side, tone, pts) in enumerate(SHARDS):
    svg.append(f'  <path class="{part} {"right" if side > 0 else "left"}" d="{poly(pts)}" style="fill:{TONES[tone]}"/>')
svg.append('</svg>')
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(svg) + "\n")

if len(sys.argv) > 2:
    rows = []
    for i, (part, side, tone, pts) in enumerate(SHARDS):
        cx, cy = centroid(pts)
        # where it flies when scattered: out from the middle, a little turned
        dx, dy = cx - C, cy - (C + 30)
        d = math.hypot(dx, dy) or 1
        fx, fy = dx / d * 70 + (i % 3 - 1) * 14, dy / d * 70 - 20 + (i % 2) * 18
        spin = ((i * 47) % 90) - 45
        wing = 1 if part in ("wing", "low") else 0
        rows.append(f'''        Shard {{ d: "{poly(pts)}"; tone: {tone}; cx: {cx:.1f}; cy: {cy:.1f}; fx: {fx:.1f}; fy: {fy:.1f}; spin: {spin}; wing: {wing * side} }}''')
    qml = f'''import QtQuick
import QtQuick.Shapes

// xvlet's mark (generated by tools/mark.py, as assets/brand/xvlet.svg):
// wings of shards in three tones. Every shard moves on its own: scatter
// (0 whole, 1 flown apart and turned), flap (degrees: the wings beat
// about the body).
Item {{
    id: root
    property color ink: "#1b1d24"
    property color ink2: Qt.tint(ink, "#40ffffff")
    property color ink3: Qt.tint(ink, "#80ffffff")
    property real scatter: 0
    property real flap: 0
    implicitWidth: 64
    implicitHeight: 64

    component Shard: Shape {{
        id: sh
        property string d
        property int tone
        property real cx
        property real cy
        property real fx
        property real fy
        property real spin
        property int wing              // 1 the right wing, -1 the left, 0 the body
        width: {S}; height: {S}
        preferredRendererType: Shape.CurveRenderer
        transform: [
            // the wing beats about the body's top
            Rotation {{ origin.x: {C}; origin.y: {C + 52}; angle: -root.flap * wing }},
            Rotation {{ origin.x: cx; origin.y: cy; angle: spin * root.scatter }},
            Translate {{ x: fx * root.scatter; y: fy * root.scatter }}
        ]
        opacity: 1 - root.scatter * .35
        ShapePath {{ strokeWidth: -1; fillColor: tone === 0 ? root.ink : tone === 1 ? root.ink2 : root.ink3; PathSvg {{ path: sh.d }} }}
    }}

    Item {{
        // the drawing's box: 340 square round the middle
        width: 340; height: 340
        transform: [ Translate {{ x: -{C - 170}; y: -{C - 150} }}, Scale {{ xScale: root.width / 340; yScale: root.height / 340 }} ]
{chr(10).join(rows)}
    }}
}}
'''
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(qml)
print("ok")
